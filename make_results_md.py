"""
Write RESULTS.md: every number reported in the paper, generated from results/results.json.

  python make_results_md.py

Regenerated, never edited by hand. WP = win probability; WPA = change in nflverse WP on that play;
pts = percentage points of WP. All 95% intervals resample whole games unless marked otherwise.
"""
import json
import os

R = json.load(open(os.path.join("results", "results.json")))
I = json.load(open(os.path.join("results", "run_info.json")))
c, wp, wk, ev, bm = R["conversion"], R["wp_model"], R["weak_cases"], R["recommendation_eval_2025"], R["nfl4th_benchmark"]
pct = lambda v: f"{v * 100:.1f}%"
ci = lambda v: f"[{v[0]}, {v[1]}]"
L = []
add = L.append
add("# Results record\n")
add(f"Generated by `make_results_md.py` from `results/results.json` (source: {I['source']}, "
    f"scikit-learn {I['packages']['scikit-learn']}, seed {I['random_seed']}). Do not edit by hand. "
    "WPA = change in nflverse win probability on the play; pts = WP percentage points. "
    "Intervals are 95% bootstrap intervals that resample whole games unless marked play-level.\n")

cl = R["cleaning"]
add("## Data\n")
add("| Item | Value |\n|---|---|")
add(f"| Plays, 2021-2025 | {cl['total_plays']:,} |")
add(f"| Fourth-down decisions kept | {cl['clean_rows']:,} (punt {cl['decision_counts']['punt']:,}, FG {cl['decision_counts']['field_goal']:,}, go {cl['decision_counts']['go']:,}) |")
add(f"| Go attempts train 2021-24 / test 2025 | {R['n_train_go']:,} / {R['n_test_go']:,} ({R['n_test_go_games']} games) |")
add(f"| WP training plays (2021-24) | {wp['n_train_plays']:,} |")
add(f"| 2025 regulation fourth downs (decision tests) | {ev['final']['n_plays']:,} ({ev['final']['n_games']} games) |\n")

add("## T1. Conversion prediction (931 held-out 2025 go attempts)\n")
names = {"constant_rate": "League rate (baseline)", "distance_bucket": "Distance-bucket rate (baseline)",
         "logistic_regression": "Logistic regression", "random_forest": "Random forest",
         "gradient_boosting": "Gradient boosting", "situation_neutral_lr": "Situation-neutral LR (engine)",
         "situation_neutral_lr_with_deep_fix": "Situation-neutral LR + sparse-region fix"}
cv = c["cv_brier_2021_24_leave_one_season_out"]
add("| Method | Accuracy | ROC-AUC | Brier | CV Brier 2021-24 |\n|---|---|---|---|---|")
for k, n in names.items():
    m = c["test_2025"][k]
    add(f"| {n} | {pct(m['accuracy'])} | {m['roc_auc']:.3f} | {m['brier']:.3f} | {cv.get(k, '-')} |")
b = c["chosen_vs_distance_bucket_bootstrap"]
add(f"\nChosen by CV: {c['chosen_by_cv']}. Chosen minus distance baseline ({b['n_games']} games): AUC {ci(b['auc_diff_ci95'])}, "
    f"Brier {ci(b['brier_diff_ci95'])}; play-level AUC {ci(b['auc_diff_ci95_play_level'])}, Brier {ci(b['brier_diff_ci95_play_level'])}.\n")

add("## T2. Win-probability models (2025 regulation plays)\n")
add("| Model | All plays | Last 5 min | Red zone |\n|---|---|---|---|")
for k, lab in [("v1", "v1 (checkpoint)"), ("v2", "v2 (final)")]:
    w = wp[k]
    add(f"| {lab} | {w['brier_ours']} | {w['brier_ours_last5min']} | {w['brier_ours_redzone']} |")
w = wp["v2"]
add(f"| nflverse published WP | {w['brier_nflverse_wp']} | {w['brier_nflverse_last5min']} | {w['brier_nflverse_redzone']} |")
add(f"\nPlays: all {w['n_plays_2025']:,}, last 5 min {w['n_last5min']:,}, red zone {w['n_redzone']:,}. "
    "Grouped-CV selection on 2021-24 is in `results/tune_wp_output.txt`.\n")

add("## T3-T5. Recommendation tests (2025)\n")
add("| Measure | Rule | Checkpoint engine | Final engine | WP-fix-only | 5-feature conversion |\n|---|---|---|---|---|---|")
E = ["checkpoint", "final", "wp_fix_only", "full_conv"]
rc = lambda d: f"{d.get('go', 0):,} / {d.get('field_goal', 0):,} / {d.get('punt', 0):,}"
add(f"| Recommends go / FG / punt | {rc(ev['final']['rule_recommends'])} | " + " | ".join(rc(ev[e]['model_recommends']) for e in E) + " |")
add(f"| Agreement with teams | {pct(ev['final']['agreement_rule_vs_teams'])} | " + " | ".join(pct(ev[e]['agreement_model_vs_teams']) for e in E) + " |")
ar = ev["final"]["association"]["rule"]
add(f"| T3 gap by group, pts | {ar['weighted_gap_pp']} {ci(ar['weighted_gap_ci95_game'])} | " +
    " | ".join(f"{ev[e]['association']['engine']['weighted_gap_pp']} {ci(ev[e]['association']['engine']['weighted_gap_ci95_game'])}" for e in E) + " |")
add(f"| T3 gap by group, play-level CI | {ci(ar['weighted_gap_ci95_play_level'])} | " +
    " | ".join(ci(ev[e]['association']['engine']['weighted_gap_ci95_play_level']) for e in E) + " |")
add(f"| T3 situation-matched, pts | {ar['matched_gap_pp']} {ci(ar['matched_gap_ci95_game'])} | " +
    " | ".join(f"{ev[e]['association']['engine']['matched_gap_pp']} {ci(ev[e]['association']['engine']['matched_gap_ci95_game'])}" for e in E) + " |")
add(f"| Share of plays usable for matching | {ar['matched_share_of_plays_used']} | " +
    " | ".join(str(ev[e]['association']['engine']['matched_share_of_plays_used']) for e in E) + " |")
add("| Engine minus rule, by group / matched | | " +
    " | ".join(f"{ci(ev[e]['association']['engine_minus_rule']['weighted_gap_diff_ci95_game'])} / {ci(ev[e]['association']['engine_minus_rule']['matched_gap_diff_ci95_game'])}" for e in E) + " |")
for k, lab in [("go", "GO"), ("field_goal", "FG"), ("punt", "PUNT")]:
    add(f"| T3 per group: said {lab} | {ar['per_group_gap_pp'][k]} {ci(ar['per_group_gap_ci95_game'][k])} | " +
        " | ".join(f"{ev[e]['association']['engine']['per_group_gap_pp'][k]} {ci(ev[e]['association']['engine']['per_group_gap_ci95_game'][k])}" for e in E) + " |")
add("| Clear GO calls (margin >= 3 pts): n, WPA went vs kicked | | " +
    " | ".join(f"{ev[e]['clear_go_calls']['n']}: {ev[e]['clear_go_calls']['wpa_went']:+.2f} vs {ev[e]['clear_go_calls']['wpa_kicked']:+.2f}" for e in E) + " |")
add("| Margin labels: toss-up / lean / clear | | " +
    " | ".join(f"{ev[e]['margin_labels'].get('toss_up', 0)} / {ev[e]['margin_labels'].get('lean', 0)} / {ev[e]['margin_labels'].get('clear', 0)}" for e in E) + " |")
add("| T4 predicted vs nflverse post-play WP (go, FG, punt) | | " +
    " | ".join(", ".join(f"{ev[e]['value_consistency_check'][k]['mean_predicted']:.3f}/{ev[e]['value_consistency_check'][k]['mean_nflverse_after']:.3f}" for k in ["go", "field_goal", "punt"]) for e in E) + " |")
add("| T5 changed by game state | 0 | " +
    " | ".join(f"{ev[e]['sensitivity']['changed_when_score_time_neutralized']:,} ({pct(ev[e]['sensitivity']['share'])})" for e in E) + " |\n")

add("## External benchmark: nfl4th (same 2025 plays)\n")
if bm.get("available"):
    a = bm["association"]
    add(f"Matched plays: {bm['n_matched']:,} of {bm['n_engine_plays']:,}. nfl4th recommends go / FG / punt: {rc(bm['nfl4th_recommends'])}.\n")
    add("| Recommender | Gap by group | Situation-matched |\n|---|---|---|")
    for k, lab in [("rule", "Rule"), ("nfl4th", "nfl4th"), ("engine", "Final engine")]:
        add(f"| {lab} | {a[k]['weighted_gap_pp']} {ci(a[k]['weighted_gap_ci95_game'])} | {a[k]['matched_gap_pp']} {ci(a[k]['matched_gap_ci95_game'])} |")
    for k in ["engine_minus_nfl4th", "engine_minus_rule", "nfl4th_minus_rule"]:
        add(f"\n- {k}: by group {ci(a[k]['weighted_gap_diff_ci95_game'])}, matched {ci(a[k]['matched_gap_diff_ci95_game'])}")
    ag = bm["agreement"]
    add(f"\nAgreement: engine vs nfl4th {pct(ag['engine_vs_nfl4th'])}, rule vs nfl4th {pct(ag['rule_vs_nfl4th'])}, "
        f"teams vs nfl4th {pct(ag['teams_vs_nfl4th'])}. Disagreements {bm['disagreements']['n']}: engine GO / nfl4th kick "
        f"{bm['disagreements']['engine_go_nfl4th_kick']}, engine kick / nfl4th GO {bm['disagreements']['engine_kick_nfl4th_go']}.\n")

add("## Weak cases, before and after the fixes\n")
add("| Item | Checkpoint | WP fix only | Final |\n|---|---|---|---|")
f1 = lambda e: wk[e]["weak_case_1_4th5_own10_tied_Q2"]
f2 = lambda e: wk[e]["weak_case_2_4th8_opp30_down4_2min"]
add("| Case 1: 4th & 5 own 10, tied, Q2 | " + " | ".join(
    f"{f1(e)['recommendation'].upper()} (go {pct(f1(e)['wp_go'])} vs punt {pct(f1(e)['wp_punt'])}; p {pct(f1(e)['p_convert'])})" for e in ["checkpoint", "wp_fix_only", "final"]) + " |")
add("| Case 2: 4th & 8 opp 30, down 4, 2:00 | " + " | ".join(
    f"{f2(e)['recommendation'].upper()} (go {pct(f2(e)['wp_go'])}, FG {pct(f2(e)['wp_field_goal'])})" for e in ["checkpoint", "wp_fix_only", "final"]) + " |")
add("| 2025 GO calls own 15 or deeper, 4th & 3-6 (teams punted) | " + " | ".join(
    f"{wk[e]['2025_go_calls_own15_or_deeper_ytg3to6']['n']} ({wk[e]['2025_go_calls_own15_or_deeper_ytg3to6']['teams_punted']})" for e in ["checkpoint", "wp_fix_only", "final"]) + " |")
do = wk["deep_offset"]
add(f"\nSparse-region fix: 2021-24 attempts from own 15 or deeper n={do['n']}, observed {pct(do['observed_rate'])}, "
    f"model mean {pct(do['model_mean_p'])}, logit offset {do['logit_offset']:.3f} (K={do['k']}). "
    f"2025 attempts there: n={do['test_2025_deep_attempts']['n']}, converted {pct(do['test_2025_deep_attempts']['actual_rate'])}.\n")
for v in ["v1", "v2"]:
    cv_ = wk[f"wp_{v}_curves"]
    add(f"- WP {v}: opponent 1st-down WP by yards from goal {cv_['opp_wp_1st_down_by_yards_from_goal']}; "
        f"gap 5 vs 20 yards {cv_['gap_5_vs_20_yards_pts']} pts; opponent leading by 1 / by 4 with 1:50 left at own 30: "
        f"{cv_['opp_leading_by_1_vs_4_with_1m50_left_own30']}")
sb = wk["selection_bias_4th6_own28_tied_Q1"]
add(f"\nSelection bias, 4th & 6 at own 28, tied, Q1: " + ", ".join(f"{k} {pct(v)}" for k, v in sb["model_predictions"].items())
    + f"; league rate at 6 yards {pct(sb['league_rate_at_6_yards_2021_24'])}.")
open("RESULTS.md", "w").write("\n".join(L) + "\n")
print("Wrote RESULTS.md")
